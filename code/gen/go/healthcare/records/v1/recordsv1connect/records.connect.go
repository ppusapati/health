// Medical records and health information management: chart completion,
// deficiency tracking, clinical coding, record release, retention and legal
// holds, physical record tracking, statutory certificates and the accounting
// of disclosures.
//
// Owning context : records  (Master Engineering Registry)
// Owning service : RecordsService
// Trace          : SRS-MRD-001 … SRS-MRD-010
//
// Five shapes in this contract are deliberate.
//
// Nothing here carries clinical text. A ChartDocument has an identifier, a
// kind, a signature and a timestamp, and no body; an AssignedCode has a
// system, a value and the identifier of the document it was read from, and no
// narrative. SRS-MRD-003 and SRS-MRD-008 both turn on health information
// management being unable to change what a clinician wrote, and the way to
// mean that in a contract is to have no field that could carry it and no RPC
// that could write one.
//
// A deficiency is resolved by naming the document that answered it, and for
// an inadequate document that must be a different document. An addendum
// answers a bad discharge summary; an edit would rewrite signed history, and
// this contract cannot express one.
//
// A coded episode is a list of revisions, never a single current coding. A
// payer asking why a claim changed is asking what the coding used to be, and
// a contract that returned only the latest could not answer.
//
// A release request carries its authority, its purpose, its recipient and its
// scope, and the package that went out is returned item by item with a
// content hash. "We sent them the record" is not an answer to a complaint;
// "we sent these forty-one documents, hashed thus, under this consent" is.
//
// Every completion figure carries an "unanswerable" flag rather than
// reporting zero against an empty denominator, and counts waivers separately
// from completions. A hospital that counts waived deficiencies as completed
// charts can reach a hundred per cent by waiving.

