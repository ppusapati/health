// Billing, tariffs and patient revenue: the charge master, tariff contracts,
// packages, charges, invoices, the account ledger and cashier shifts.
//
// Owning context : billing  (Master Engineering Registry)
// Owning service : BillingService
// Trace          : SRS-BIL-001 … SRS-BIL-016
//
// Three shapes in this contract are deliberate and worth reading before using
// it.
//
// Money is an int64 count of minor units with its currency beside it, never a
// double and never a decimal string. A double cannot represent 0.10 exactly, so
// a hundred lines summed as doubles do not equal the invoice total — and an
// invoice that does not add up is one a patient is right to dispute. A tariff
// of 1,250.50 is 125050.
//
// An invoice carries its own totals rather than leaving a client to sum the
// lines. The lines are a snapshot taken at issue, and the totals are what the
// document said: a client that recomputed would eventually round differently
// and show a patient a figure the hospital never charged.
//
// CloseAccountResponse returns the blocking exceptions rather than a boolean.
// SRS-BIL-013's acceptance is that they are listed, and a biller told "the
// account cannot be closed" has to go looking for what is usually one held
// charge out of four hundred.

