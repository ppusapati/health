// The operating theatre: rooms and lists, the surgery request, scheduling,
// the checklists, patient movement, the command board, the operative note and
// traceability.
//
// Owning context : theatre  (Master Engineering Registry)
// Owning service : TheatreService
// Trace          : SRS-OT-001 … SRS-OT-017
//
// Four shapes in this contract are deliberate.
//
// Laterality is a field of its own, never a word in the procedure name.
// Wrong-site surgery is the never-event the checklists exist to prevent, and
// "left" buried in a sentence is not something a client or a server can check.
//
// A booking attempt returns every conflict, and marks each one overridable or
// not. A scheduler told one clash at a time rebooks once per clash while a
// list is being built; and a hard clash — another case in the room, the
// surgeon operating elsewhere — is refused whatever the caller asks, because
// overriding it does not make a second theatre appear.
//
// Nothing carries a stored duration. Turnover, operating time and on-time
// starts are computed per response from the milestones, because SRS-OT-015
// says metrics reconcile to recorded timestamps — and an interval whose
// milestones have not both happened is absent rather than zero.
//
// A cancellation carries a coded cause. SRS-OT-005 asks analytics to
// distinguish patient, clinical, resource and administrative causes, and the
// fixes for "no bed" and "patient did not attend" are different departments'
// work.

