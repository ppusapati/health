// Materials, procurement and inventory: the item, supplier and lot masters,
// requisition and approval, quotation and comparison, the purchase order and
// its amendments, goods receipt and inspection, the stock ledger, picking,
// issue and return, transfers, counts, blocked lots and their recall, the
// three-way match and the inventory KPIs.
//
// Owning context : materials  (Master Engineering Registry)
// Owning service : MaterialsService
// Trace          : SRS-MAT-001 … SRS-MAT-016
//
// Six shapes in this contract are deliberate.
//
// There is no on-hand field on an item. A balance is always a line in a
// ledger-derived list, keyed by location and status, because SRS-MAT-007's
// acceptance is that on-hand is derivable from immutable movements. A single
// on-hand number on the wire would be a second answer to "what do we hold",
// and it would eventually disagree with the first.
//
// A movement names a source bucket and a destination bucket, and a bucket is a
// location plus a status. In-transit is one of those statuses rather than a
// flag on a transfer, so stock that has left one store and not arrived at the
// next is somewhere rather than nowhere.
//
// Money is minor units and a currency, never a float and never a bare number.
// A rupee is a hundred paise, and two identical orders that total differently
// because of binary fractions is a defect a hospital finds in an audit.
//
// A purchase order line carries both a purchase quantity and a pack size. This
// is the conversion an invoice check gets wrong by eye: a quote per box of a
// hundred against a quote per piece differ by two orders of magnitude.
//
// An approval step names both the role required and the person who decided.
// "The head of department approved it" and "somebody holding their permission
// approved it" are different claims, and only the second is checkable.
//
// A pick is a recommendation with what it left out. The person at the shelf
// can see a crushed box; what the system owes them is the right order and an
// honest account of why a full shelf produced a short pick.

