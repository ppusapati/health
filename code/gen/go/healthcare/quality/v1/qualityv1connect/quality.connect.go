// Quality management: incident and near-miss reporting, risk scoring, root
// cause analysis, corrective and preventive action, sentinel events, document
// control, internal audit, committees, the accreditation evidence map, the
// indicator dictionary, complaints, peer review, competency and legal hold.
//
// Owning context : quality  (Master Engineering Registry)
// Owning service : QualityService
// Trace          : SRS-QMS-001 … SRS-QMS-015
//
// Seven shapes in this contract are deliberate.
//
// An incident's reach is three states rather than a near-miss flag beside a
// harm level. Two fields that can contradict each other will, and the
// contradiction is the one that matters: a near miss filed with harm is a
// mis-filed record either way, and every report built on it is wrong.
//
// The risk score and band are read-only on the wire. They come from the
// consequence and the likelihood, and a score a reporter could type is a score
// a reporter could type low.
//
// A restricted incident is returned redacted rather than withheld. A ward
// needs to know that something of this kind happened in it; what it must not
// have is the narrative, the patient and the people. A restricted analysis or
// set of minutes is withheld instead, because they are the discussion and
// there is nothing left to return.
//
// A corrective action carries every effectiveness check, including the ones
// that failed. "Fixed, checked, had not worked, fixed again, checked, had" is
// the history that tells a hospital whether its analysis was any good, and a
// single boolean keeps only the last word of it.
//
// A document version carries its own effective date and there is no "current"
// flag. The version in force is derived from the dates, because a flag needs a
// job to maintain it and a document control system whose current version is
// whatever a job last set will eventually show an unapproved draft as policy.
//
// An indicator value carries the dictionary revision it was computed under.
// SRS-OPSNFR-008 requires quality indicators be reproducible from source
// records, and an indicator edited in place turns its own history into two
// different measurements plotted on one line.
//
// A measurement with a zero denominator is marked unanswerable rather than
// reported as zero. "No eligible cases this month" and "we failed every case
// this month" are opposite facts, and a zero says the second.

