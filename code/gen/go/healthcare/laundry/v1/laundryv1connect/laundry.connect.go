// Laundry and linen: the linen item master and unit par levels, soiled
// collection and its chain to the wash, wash batches and their outcomes,
// clean linen issue and the balance derived from it, condemned, damaged and
// missing linen, and tagged high-value linen and uniforms.
//
// Owning context : laundry  (Master Engineering Registry)
// Owning service : LaundryService
// Trace          : SRS-LND-001 … SRS-LND-007
//
// Four shapes in this contract are deliberate.
//
// IssueLinen takes a batch identifier and refuses one that did not pass.
// There is no field on the request that could assert the wash was fine, and
// no RPC that issues linen without naming a batch. A wash that failed — the
// temperature never held, the machine aborted, the disinfection stage was
// skipped — produces linen that looks exactly like clean linen, and the ward
// it reaches cannot tell by looking. The database holds the same rule through
// a composite foreign key that cannot go stale: a batch cannot be moved out
// of "passed" while linen issued from it exists.
//
// RecountCollection is refused for a collection of soil class INFECTED, and
// no other RPC touches its declared lines. SRS-LND-005 asks that the worklist
// visibly identify the required handling; what makes that real is that the
// handling is derived from the class and travels on the collection, and that
// re-counting means opening a bag nobody is going to open. The declaration
// made at the bedside is the only count anybody is going to get, and a
// contract that offered a correction would be a contract where somebody was
// asked to make one.
//
// LoadBatch refuses infected linen into anything but a barrier cycle, on both
// sides: the collection carries the cycle it went into and the batch carries
// whether it holds infected linen. A standard programme does not dissolve the
// water-soluble inner bag and does not reach disinfection temperature, so the
// load comes out contaminated and indistinguishable from clean.
//
// A write-off moves no balance until somebody other than its reporter
// approves it. ApproveLinenLoss is its own RPC under its own permission, and
// GetUnitStock counts only approved records — a reported loss nobody has
// decided on is not yet a loss, and counting it as one would let a ward's
// shortfall be cleared by anybody who can type a number.
//
// Every measurement is an integer in a base unit: weights in grams,
// temperatures in whole degrees, values in the tenant's minor currency units.

