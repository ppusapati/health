// Infection prevention and control: surveillance cases and their onset
// classification, device-day denominators, isolation and the bed board,
// multidrug-resistant organism alerting, outbreak investigation, hand hygiene
// audit, occupational exposure, antimicrobial stewardship and environmental
// testing.
//
// Owning context : infection  (Master Engineering Registry)
// Owning service : InfectionService
// Trace          : SRS-IPC-001 … SRS-IPC-010
//
// Six shapes in this contract are deliberate.
//
// A case's onset classification is read-only on the wire. It is derived from
// the admission and onset dates against the configured surveillance window,
// and a classification a reporter could type is a classification a reporter
// could type "community acquired" — which does not move an infection between
// reports, it removes it from the hospital's rate entirely.
//
// The override is a separate field with its own reason, its own permission
// and its own RPC. A report that cannot tell a derived classification from an
// overridden one cannot audit its own rates.
//
// A board entry carries the precaution, the PPE and whether a side room is
// needed, and there is no field on it for the reason. A board is a screen on
// a wall that visitors and contractors walk past, and the reason a patient is
// isolated is a diagnosis.
//
// A hand hygiene observation has no field naming the person observed. Not an
// optional one: an audit that names individuals becomes a disciplinary
// instrument, and the moment it does, observed compliance goes to ninety-nine
// per cent and stops meaning anything. Small groups come back suppressed with
// their counts blanked, because "four opportunities, one performed" against a
// night shift names somebody by arithmetic.
//
// A stewardship review carries an order reference and no field that changes a
// prescription. SRS-IPC-008's acceptance is that a review appears in the
// worklist without autonomous medication change, and this contract has
// nothing to change one with: the review holds advice, and the prescriber's
// response is recorded by a different RPC under a different permission.
//
// Every rate, compliance figure and pass rate carries an "unanswerable" flag
// rather than reporting zero when its denominator is empty. "No ventilated
// patients this month" and "no infections among our ventilated patients" are
// different facts and only one of them is good news.

