// Ambulance and fleet operations: the vehicle fleet and its crew rosters,
// readiness checks and the overrides that pass them, the dispatch queue and
// the trips that answer it, the crew's account of a journey and the handover
// that attaches it to an encounter, the location feed, and the response and
// turnaround figures derived from trip milestones.
//
// Owning context : ambulance  (Master Engineering Registry)
// Owning service : AmbulanceService
// Trace          : SRS-AMB-001 … SRS-AMB-008
//
// Four shapes in this contract are deliberate.
//
// Dispatch takes an override reason and no override flag. Sending a vehicle
// that is off the run, whose readiness check has lapsed, whose crew is not on
// duty, or that does not carry what the call needs is possible — on a bad
// night the alternative is nothing at all — but only as a named person with a
// reason, under its own permission, and it raises a notice somebody has to
// acknowledge. There is one exception with no override at all: a patient
// transport vehicle is never sent to an emergency. A van with no
// defibrillator in it does not acquire one because a duty officer typed a
// sentence, and the database holds the same rule through composite foreign
// keys onto the vehicle's kind and the request's priority.
//
// A trip's timeline is append-only. RecordTripMilestone adds a point and
// refuses one already recorded or out of order; AmendTripMilestone corrects a
// time by adding a further record that carries what it superseded, why, and
// when the correction was made. There is no RPC that edits a milestone, and
// the table takes no UPDATE and no DELETE. "The arrival time was changed
// three weeks after the complaint" is a question somebody asks, and a
// timeline holding one value per point could not answer it.
//
// AcceptHandover is its own RPC under its own permission and is refused for
// whoever gave the handover. A handover accepted by the person who gave it is
// the same claim made twice, and the patient is standing between two people
// neither of whom has taken responsibility. Accepting it is also what
// attaches the crew's account to the emergency encounter, which is what
// SRS-AMB-004 asks for.
//
// The location feed carries no patient identifier. A map of an ambulance's
// day is a list of the addresses somebody was ill at; the link to a patient
// is through the trip, behind its own permission. Every ping carries the
// moment it stops being kept, set from the deployment's retention period, and
// a deployment that has not set one records no feed at all. Reads apply the
// horizon themselves rather than trusting a purge job, and every read is
// audited.
//
// Every measurement is an integer in a base unit: coordinates in
// micro-degrees, distances in metres, durations in seconds, oxygen in bar,
// doses in the unit named beside them.

