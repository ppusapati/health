// Dietetics and kitchen operations: nutrition assessment, diet orders and
// their allergy conflicts, nutrition care plans, meal census and tray
// service, enteral and parenteral nutrition planning, and ingredient
// forecasting.
//
// Owning context : hospital.ops.diet  (Master Engineering Registry)
// Owning service : DietService
// Trace          : SRS-DIET-001 … SRS-DIET-009
//
// Four shapes in this contract are deliberate.
//
// Nothing here carries a dose, a rate or an administration. A
// NutritionSupportPlan has targets and the identifier of the order or
// prescription carrying them out, and the RPC that puts it into force takes
// that identifier and resolves it. SRS-DIET-007 is explicit that this must
// not replace medication and order controls, and the way to mean it in a
// contract is to have nothing that could express one.
//
// DispatchTray takes a tray identifier and nothing else. The order in force
// is re-read server-side at that moment rather than sent by the caller,
// because the census was taken before the production cutoff and the tray
// leaves afterwards — and in between is where a patient is made nil by mouth
// for a theatre list. A contract that let the caller assert what the diet was
// would let a stale screen send that patient breakfast. When the check stops
// a tray it comes back withheld with the reason, so the ward is told the meal
// was held rather than left to assume it went astray.
//
// A diet order with an unresolved allergy conflict comes back pending, and
// GetCurrentDietOrder never returns one. SRS-DIET-003's acceptance is that a
// conflict requires authorised resolution, and an order the kitchen can
// already see is one nobody needs to resolve.
//
// Every measurement is an integer in a base unit: height in millimetres,
// weight in grams, energy in kilocalories, fluid and volume in millilitres,
// ingredients in grams. Body mass index is returned in tenths and is derived
// from the height and weight beside it, never stored — a third number that no
// longer agrees with them is one nobody can explain.

