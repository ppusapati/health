// Sterile services / CSSD: the instrument and tray masters, receipt and chain
// of custody, the reprocessing stages, assembly against a versioned packing
// list, packaging, the sterilizer cycle and its indicators, release,
// labelling, issue and return, the case trace and the recall.
//
// Owning context : sterile  (Master Engineering Registry)
// Owning service : SterileServicesService
// Trace          : SRS-CSSD-001 … SRS-CSSD-012
//
// Five shapes in this contract are deliberate.
//
// A stage is an ordered enum and a run advances exactly one step. The order is
// the department's safety property: an instrument packed without being washed
// carries the last patient's tissue into the next one. SRS-CSSD-003 permits an
// authorised exception, so a skip is expressible — an exception that cannot be
// recorded is one that happens off the system — but it needs its own
// permission, and two stages are not skippable by anybody.
//
// A pack names the packing-list version it was assembled against, not the set.
// A revision published tomorrow must not change what today's pack was checked
// against, and the version is the only thing that could audit it.
//
// A cycle's release is a separate field from its result. A load that passed is
// not a load that was cleared: the biological indicator may still be
// incubating, and SRS-CSSD-007's clause is that a failed or uncleared load
// cannot be distributed.
//
// A label is derived, never submitted. A label typed separately is a second
// account of what is in the pack, and it is the one the scrub nurse reads. It
// carries what it could not be built from rather than rendering a blank.
//
// A recall returns every pack in the load and every case one was opened for.
// The used packs cannot come back — they went into a patient — but the case
// list is the reason the recall exists.

