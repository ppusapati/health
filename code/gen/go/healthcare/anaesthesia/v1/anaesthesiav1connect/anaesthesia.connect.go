// Anaesthesia and recovery: the pre-anaesthesia assessment, the plan, the
// intraoperative record, the airway, fluids, the handover to recovery, PACU
// scoring and discharge, the pain plan and the summary.
//
// Owning context : anaesthesia  (Master Engineering Registry)
// Owning service : AnaesthesiaService
// Trace          : SRS-ANE-001 … SRS-ANE-011
//
// Five shapes in this contract are deliberate.
//
// The ASA grade is a string, not an integer plus a boolean. The emergency
// modifier is part of the grade: "3" and "3E" are different patients, and a
// contract that split them would produce reports where they were the same.
//
// Every intraoperative value carries its source and, for a device, the
// connection state at the moment of the reading. SRS-ANE-005 asks for
// integrated data to be marked by device and connection status, and the reason
// to mark it is that somebody downstream has to be able to exclude a value
// taken while the monitor was detached.
//
// A recovery assessment names the components it could not score rather than
// scoring them zero. A partial assessment is not a low one: a zero would trap
// a patient in recovery and a full mark would discharge one.
//
// A discharge evaluation returns every refusal, not the first. A nurse who
// fixes one and is then told about the next has been made to discover the
// requirements one at a time.
//
// A summary is derived, never submitted. SRS-ANE-010's clause is "generate
// anaesthesia summary from signed source data", and a summary somebody typed
// separately is a second account that disagrees with the record by the time
// the ward reads it — and it is the version that travels.

