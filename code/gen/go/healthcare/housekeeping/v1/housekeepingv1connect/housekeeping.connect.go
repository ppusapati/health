// Housekeeping and environmental services: the cleanable location master and
// its cleaning standards, routine and terminal cleaning tasks, bed cleaning
// holds, spill and biohazard work, location scanning, and the SLA, turnaround
// and audit-compliance reports.
//
// Owning context : housekeeping  (Master Engineering Registry)
// Owning service : HousekeepingService
// Trace          : SRS-HKP-001 … SRS-HKP-008
//
// Four shapes in this contract are deliberate.
//
// RecordLocationScan takes a task identifier and the code that was read, and
// returns whether it matched. It does not return a task, it does not advance
// one, and there is no RPC anywhere here that takes a scanned code alone.
// SRS-HKP-007 is explicit that a scan does not replace user authentication,
// and the way to mean it in a contract is to have nothing that could express
// it: the caller is already authenticated and already permitted to work on
// the task, and the scan adds evidence rather than permission. A scan of the
// wrong door comes back matched=false rather than as an error, because
// somebody scanned the wrong label or the label is wrong and both are
// findings.
//
// OverrideBedHold is its own RPC under its own permission, and an overridden
// hold is its own state. SRS-HKP-003's acceptance is that a bed stays
// unavailable until the clean completes or somebody overrides it, and the two
// endings are different facts: one is a bed that was cleaned, the other is a
// bed that went back into service uncleaned because the hospital was full. A
// contract that expressed the second as the first would let a turnaround
// report say the hospital cleaned every bed.
//
// A CleaningTask of kind spill comes back with its detail and incident
// reference cleared for a caller without hkp.spill.read. The task stays on
// the worklist, because somebody still has to go and clean it; what goes is
// what was spilled and where, which is a clinical fact about whoever was in
// that bay. SRS-HKP-006's restricted category is this, not a label.
//
// A cleaning task carries its own checklist and the revision of the standard
// it was raised under, rather than a pointer to a location. SRS-HKP-001 says
// schedules derive from the active configuration; the corollary is that a
// configuration edited afterwards must not change what a completed clean was
// judged against, and a contract that returned a reference would leave the
// reader to resolve it against today's standard.

