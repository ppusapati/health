// Facilities engineering operations: the non-biomedical plant register, work
// orders and the safety paperwork that makes dangerous work safe, preventive
// and statutory maintenance, planned utility shutdowns and who they reach,
// alarms from plant gateways, fire and life-safety deficiencies, utility
// metering and downtime, and contractor attendance.
//
// Owning context : facilities  (Master Engineering Registry)
// Owning service : FacilitiesService
// Trace          : SRS-FAC-001 … SRS-FAC-011
//
// SRS-FAC-012's escalation matrix belongs to the platform escalation
// mechanism and is not repeated here. Six shapes in this contract are
// deliberate.
//
// StartWork takes the permit-to-work and lockout-tagout references, and
// CloseWork takes none. The paperwork exists to make the work safe, so it is
// demanded before the panel is opened rather than after it is back together
// — an engineer asked for a permit number at the end will find one. There is
// no field anywhere that waives it: which classes of work need a permit is
// configured once, in writing, usually after an incident, and is not re-made
// by whoever is raising the ticket.
//
// Alarm and WorkOrder are separate messages with separate lifecycles, and
// neither carries the other's state. ClearAlarm does not close work and
// CloseWork does not clear an alarm: a chiller whose alarm stopped because
// somebody cycled the power has not been repaired, and a completed job does
// not make the plant stop shouting. The link is one field on Alarm, written
// once, and there is no unlink.
//
// ListDeficiencies has no time window, and OpenCriticalDeficiencies has no
// paging cursor. SRS-FAC-008's acceptance is that open critical findings
// remain visible until closure, and a window is how a hospital stops seeing
// the stairwell it never unblocked. MitigateDeficiency exists and does not
// close anything: a fire watch is not a repair.
//
// Every reading carries its own source and source reference rather than
// inheriting the meter's, because the night the gateway was down somebody
// read the dial, and a consumption figure built partly on that says so.
//
// A contractor visit names the work order, asset or task it is for, and one
// against permit work carries the site induction. Contractors are the people
// least likely to know the building and most likely to be the ones isolating
// something.
//
// Every measurement is an integer in a base unit: minutes for response and
// downtime, days for intervals, hours for runtime counters, and the meter's
// own declared unit for a reading. No floats: a consumption figure that
// disagrees with the bill in the third decimal place is a conversation
// nobody wins.

