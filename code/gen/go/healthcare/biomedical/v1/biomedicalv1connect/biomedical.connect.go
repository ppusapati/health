// Biomedical engineering: the equipment register, service contracts,
// preventive maintenance and its due list, breakdown and service work with
// contract-derived SLAs, calibration, recalls and field safety notices,
// device telemetry, uptime and reliability figures, the link from equipment
// availability to what a room can be scheduled for, and disposal.
//
// Owning context : biomedical  (Master Engineering Registry)
// Owning service : BiomedicalService
// Trace          : SRS-BIO-001 … SRS-BIO-011
//
// Six shapes in this contract are deliberate.
//
// A ticket carries a kind, and only a corrective one is a failure. MTBF is
// the mean time between failures; counting a scheduled service as one makes a
// well-maintained machine look unreliable, which would be an argument for
// servicing less. Planned downtime is reported beside the unplanned kind
// rather than mixed into it.
//
// A ticket's SLA hours are read-only on the wire. They are derived from the
// asset's live contract and tightened by priority, and a request that could
// set them could give itself a week for an emergency.
//
// A disposal names a requester but not an approver. The approver is the
// authenticated caller, because an approval field a client can fill in is an
// approval the requester grants themselves.
//
// A location's capability is a map of counts, not a list of flags. A theatre
// with two image intensifiers loses nothing when one goes for service, and a
// boolean would take the room off the list.
//
// Expiries and the maintenance due list have no "create" RPC. Both are
// derived on read, because a stored reminder stays raised after the contract
// is renewed and an engineer who has learned to ignore stale reminders
// ignores the real one too.
//
// A runtime maintenance plan with no meter reading is reported as
// unanswerable rather than as not-due. "We do not know" and "it is fine" are
// different answers, and only one of them needs somebody to go and look.

