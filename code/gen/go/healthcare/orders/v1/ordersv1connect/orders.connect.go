// Orders and CPOE: one framework across nine order types, order sets,
// favourites, duplicate detection and downstream routing.
//
// Owning context : orders  (Master Engineering Registry)
// Owning service : OrderService
// Trace          : SRS-ORD-001 … SRS-ORD-012
//
// Two shapes in this contract are deliberate and worth reading before using it.
//
// PlaceOrderResponse returns an order *or* a duplicate warning, never both.
// SRS-ORD-009 requires a warning "rather than arbitrary suppression", so a
// first attempt comes back with the live orders that already exist and places
// nothing; a second, carrying the clinician's reason, places the order.
//
// CancelOrderResponse says whether the order was withdrawn or a cancellation
// was *requested*. SRS-ORD-004 rejects cancelling an order the performing
// service has already started, and converts it to a request the service
// answers — so a client that assumed cancellation always succeeds would tell a
// ward that a transfusion had stopped when it had not.

