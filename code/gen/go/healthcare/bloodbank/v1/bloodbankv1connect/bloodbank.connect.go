// Blood bank and transfusion medicine: donors, screening, collection, testing,
// inventory, requests, compatibility, reservation, issue, the bedside check,
// the transfusion, reactions, traceability, stock and utilisation.
//
// Owning context : bloodbank  (Master Engineering Registry)
// Owning service : BloodBankService
// Trace          : SRS-BLD-001 … SRS-BLD-017
//
// Five shapes in this contract are deliberate.
//
// ABO and Rh are separate enums with explicit unspecified members, and
// unspecified is never a match. "We have not grouped this patient" and "group
// O" are different states, and a contract that let them collapse would issue
// the wrong blood. A component always carries a real group; a patient carries
// theirs on a sample, whose absence is what "ungrouped" means.
//
// A compatibility search returns every candidate with its verdict rather than
// a pre-filtered list. A scientist looking at a near-miss — right group, wrong
// special requirement — needs to see it and why, because the alternative is a
// screen that says "no units available" beside a full fridge.
//
// An issue carries either a reservation or an emergency authorisation. That is
// SRS-BLD-009 and SRS-BLD-016 in one message: a unit leaves because it was
// crossmatched for somebody, or because a named senior clinician said so and
// gave a reason. There is no third field.
//
// The bedside check is its own RPC as well as being run inside StartTransfusion.
// A client can show the result before the nurse commits, and a failed check is
// recorded as a critical exception whether or not anybody then proceeds —
// which is what SRS-BLD-010's "generates critical exception" asks for. The
// check inside the start is the one that counts: it runs from rows read in the
// same transaction, so nothing can change between verifying and starting.
//
// Nothing here stores a utilisation figure. SRS-BLD-015 says reports derive
// from recorded issues, transfusions and reactions, and a counter kept
// alongside them drifts the first time anything is corrected.

