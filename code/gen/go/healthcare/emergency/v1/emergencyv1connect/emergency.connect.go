// The Emergency Department: arrival, triage, the queue, time-critical
// pathways, the resuscitation timeline and disposition.
//
// Owning context : emergency  (Master Engineering Registry)
// Owning service : EmergencyService
// Trace          : SRS-ER-001 … SRS-ER-018
//
// Three shapes in this contract are deliberate.
//
// An EmergencyVisit carries an encounter_id and no episode of its own. A visit
// is the emergency detail of a Wave-1 encounter rather than a second kind of
// encounter: the patient, the allergies and the episode all belong to the
// encounter, and a department holding its own copy is a department whose chart
// disagrees with the ward's.
//
// An Event carries occurred_at and recorded_at separately, and the timeline
// sorts on the first. A resuscitation is written up in arrears more often than
// not, and the gap between the two is the only thing that distinguishes a
// contemporaneous record from a reconstruction. `late` is derived from that gap
// and travels, so a client cannot render the two alike.
//
// Nothing carries a door-to-triage or door-to-doctor interval as a stored
// field. SRS-ER-006 says the dashboard "derives times from immutable events",
// and the Intervals message below is computed per response. Its fields are
// optional on purpose: an absent door-to-doctor means nobody has seen the
// patient, and a zero would be the number that makes a dashboard look best
// while the department is at its worst.

