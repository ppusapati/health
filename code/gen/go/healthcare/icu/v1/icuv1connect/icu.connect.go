// Critical care: the episode, the flowsheet, organ support, scores, bundles,
// the ceiling of treatment and the unit dashboard.
//
// Owning context : icu  (Master Engineering Registry)
// Owning service : IcuService
// Trace          : SRS-ICU-001 … SRS-ICU-017
//
// Four shapes in this contract are deliberate.
//
// An Observation carries the value twice: normalised, and as it arrived, with
// `normalised` false where the unit was not one this system converts. A
// conversion is a transformation, and a client that cannot show what the
// device actually sent cannot be audited against it. A number in the wrong
// unit that looks right is worse than one that is visibly unconverted.
//
// A Score carries its formula version and every input it used, each naming the
// observation it read. SRS-ICU-009 requires the score to be reproducible from
// them, so a total on its own would be a claim nobody can check — and
// `missing` is what makes an incomplete score readable as incomplete rather
// than as a low one.
//
// An Alarm here is a worklist entry. There is no field that would change what
// a bedside device does: no limit, no suppression, no silence. SRS-ICU-013 is
// explicit that this software's alarms are advisory and cannot suppress
// device-native safety behaviour, and the contract is where that has to be
// visible to everyone who builds against it.
//
// A DashboardRow's ceiling of treatment is either present or marked
// `ceiling_restricted`. An absent one would read as "no ceiling agreed", and
// the difference between that and "you may not see it" is what gets a patient
// resuscitated against their wishes.

