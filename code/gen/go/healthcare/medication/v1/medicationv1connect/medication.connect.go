// Medication management: structured prescribing, safety screening,
// reconciliation, pharmacist verification, substitution and formulary.
//
// Owning context : medication  (Master Engineering Registry)
// Owning service : MedicationService
// Trace          : SRS-MED-001 … SRS-MED-014
//
// Three shapes in this contract are deliberate and worth reading before using
// it.
//
// A Prescription carries an order_id and an order_number. A prescription is the
// clinical detail of a medication order rather than a second kind of order: the
// number a ward reads down a phone, the routing to the pharmacy and the order
// lifecycle all belong to the order context, and the two identifiers are how a
// client joins them.
//
// therapy_status is not the order's status. It answers "is the patient on this
// drug right now", where the order's answers "where has the supply request got
// to". A drug held for a procedure is a therapy that has stopped and a supply
// request that has not; a course dispensed in full on Monday is a supply
// request that is finished and a therapy that runs until Friday.
//
// PrescribeResponse does not return warnings in the success case. A prescription
// blocked by unanswered safety findings comes back as a FAILED_PRECONDITION
// whose field violations carry every finding, its rule and its rule version —
// so a client shows all of them at once rather than one at a time, and a
// prescriber who answers the first does not then discover a second.

